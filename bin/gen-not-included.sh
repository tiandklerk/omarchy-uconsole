#!/usr/bin/env bash
# Regenerate docs/03-not-included.md from the triage and, if stage 30 has run,
# the actual build report. Keeps the "what's missing" document honest instead of
# hand-maintained.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/../config/build.env"
source "$HERE/lib.sh"

TRIAGE="$HERE/../packages/triage.tsv"
REPORT="$OUT_DIR/packages/build-report.tsv"
DOC="$HERE/../docs/03-not-included.md"
require_file "$TRIAGE" "run bin/triage-packages.sh first"

{
cat <<'HEAD'
# What's not included

Omarchy assumes an x86_64 laptop. This is everything from its package lists that
does not come along to a CM5 uConsole, and why.

This file is generated by `bin/gen-not-included.sh` from `packages/triage.tsv`
and `packages/excluded.packages`. Don't edit it by hand.

## Summary
HEAD

printf '\n| Verdict | Count |\n|---|---|\n'
awk -F'\t' 'NR>1{c[$2]++} END{
  printf "| Already in Arch Linux ARM aarch64 | %d |\n", c["alarm"]
  printf "| Dropped (see below) | %d |\n", c["drop"]
  printf "| Built here from omarchy-pkgs | %d |\n", c["omarchy"]
  printf "| Built here from the AUR | %d |\n", c["aur"]
}' "$TRIAGE"

cat <<'MID'

## Dropped features

Three things are missing that are not merely a package:

**Snapshot rollback from the boot menu.** Omarchy pairs btrfs snapshots with
limine boot entries so a bad update can be backed out at boot. The CM5 has no
BIOS or UEFI — its bootloader is in SPI EEPROM and reads `config.txt` — so there
is no boot menu to add entries to. We ship ext4 and no snapper. Rolling back an
update means reflashing, or restoring from your own backups.

**Hardware video encode/decode.** Omarchy's screen recording and video tooling
lean on VAAPI via Intel or NVIDIA drivers. The CM5 has neither. The VideoCore
VII has its own decode path, but nothing here is wired up to use it, so
`obs-studio` and `gpu-screen-recorder` will fall back to software encoding if
they run at all — on four A76 cores, expect that to be slow.

**The 4G modem.** Some uConsoles have one. Rex ships a Debian `uconsole-4g`
package; no Arch equivalent has been written and ModemManager is not installed.

## Dropped packages

Every package below is in Omarchy's own lists and deliberately excluded.

MID

printf '| Package | Reason |\n|---|---|\n'
awk -F'\t' '$2=="drop"{printf "| `%s` | %s |\n", $1, $4}' "$TRIAGE" | sort

cat <<'MID2'

## Packages built for aarch64 here

These do not exist in the Arch Linux ARM repositories, so stage 30 builds them.

MID2

printf '| Package | Source |\n|---|---|\n'
awk -F'\t' '$2=="omarchy"{printf "| `%s` | omarchy-pkgs |\n", $1}' "$TRIAGE" | sort
awk -F'\t' '$2=="aur"{printf "| `%s` | AUR |\n", $1}' "$TRIAGE" | sort

if [[ -f "$REPORT" ]]; then
  cat <<'MID3'

## Build results

What actually happened the last time stage 30 ran on this machine.

MID3
  printf '| Package | Status | Detail |\n|---|---|---|\n'
  awk -F'\t' 'NR>1{printf "| `%s` | %s | %s |\n", $1, $2, $3}' "$REPORT"
  printf '\nA package that failed here is simply absent from the image; the rest\nof Omarchy is unaffected.\n'
else
  cat <<'MID4'

## Build results

Stage 30 has not been run on this checkout yet. Once it has,
`bin/gen-not-included.sh` adds a table here recording which of the packages
above actually built for aarch64 and which failed.
MID4
fi
} > "$DOC"

ok "wrote $DOC ($(wc -l < "$DOC") lines)"
